/// Add `entry.shape_note` — how the shape of an unencodable glyph was described.
///
/// A separate statement rather than a column on [`create_entry_table`], because the schema
/// migration has already run on live databases: editing an applied migration would leave
/// them without the column while the code expected it.
///
/// Nullable on purpose, and it stays `NULL` for every entry that has a glyph. It is filled
/// only for the 29 entries where the 2026 edition sets an image, and only from a dossier row
/// a person has signed — see the import step. Nothing describes a shape on its own authority.
pub fn add_entry_shape_note() -> TableAlterStatement {
    Table::alter()
        .table(Entry::Table)
        .add_column_if_not_exists(ColumnDef::new(Entry::ShapeNote).text())
        .to_owned()
}

/// Undo [`add_entry_shape_note`].
pub fn drop_entry_shape_note() -> TableAlterStatement {
    Table::alter()
        .table(Entry::Table)
        .drop_column(Entry::ShapeNote)
        .to_owned()
}
