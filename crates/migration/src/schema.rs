// ── Generated column expressions ─────────────────────────────────────────────

/// `to_tsvector('vi_simple'::regconfig, coalesce(<column>, ''))`
///
/// **Why not `PgFunc::to_tsvector`:** that function takes `regconfig` as a **`u32` OID**,
/// and the OID of `vi_simple` only exists once the configuration has been created — it
/// cannot be known while writing the migration. This uses the cast `'vi_simple'::regconfig`
/// instead, still fully typed via [`Func::cast_as`], letting Postgres resolve the OID at parse time.
fn to_tsvector(column: Entry) -> Expr {
    Func::cust(PgFn::ToTsvector)
        .arg(Func::cast_as(ts_config_literal(), PgType::RegConfig))
        .arg(Func::cust(PgFn::Coalesce).arg(Expr::col(column)).arg(""))
        .into()
}

/// `setweight(<expression>, '<rank>')`
fn setweight(expr: Expr, weight: &str) -> Expr {
    Func::cust(PgFn::Setweight).arg(expr).arg(weight).into()
}

/// The `search_doc` column, concatenated with weights.
///
/// The three weight ranks match the three ways users search:
/// **A** the reading (forward lookup) · **B** the main definition · **C** sub-entry text (reverse lookup).
///
/// `sub_text` has to be a column of the `entry` table itself: a Postgres generated column
/// cannot reference another table, so `sub_entry` cannot be folded in directly.
fn search_doc_expr() -> Expr {
    setweight(to_tsvector(Entry::Reading), "A")
        .binary(
            PgBinOper::Concatenate,
            setweight(to_tsvector(Entry::Gloss), "B"),
        )
        .binary(
            PgBinOper::Concatenate,
            setweight(to_tsvector(Entry::SubText), "C"),
        )
}

// ── Indexes ────────────────────────────────────────────────────────────────────

/// GIN on `search_doc` — the full-text search index.
pub fn create_search_doc_index() -> IndexCreateStatement {
    Index::create()
        .name(IdxName::EntrySearchDoc.into_iden().to_string())
        .table(Entry::Table)
        .col(Entry::SearchDoc)
        .index_type(IndexType::Custom(IdxMethod::Gin.into_iden()))
        .to_owned()
}

/// GIN + `gin_trgm_ops` on `reading_norm` — for unaccented search and typo suggestions.
pub fn create_reading_norm_trgm_index() -> IndexCreateStatement {
    Index::create()
        .name(IdxName::EntryReadingNormTrgm.into_iden().to_string())
        .table(Entry::Table)
        .col(IndexColumn::from(Entry::ReadingNorm).with_operator_class(OpClass::GinTrgm))
        .index_type(IndexType::Custom(IdxMethod::Gin.into_iden()))
        .to_owned()
}

/// B-tree on `reading` — exact and prefix lookup.
pub fn create_reading_index() -> IndexCreateStatement {
    Index::create()
        .name(IdxName::EntryReading.into_iden().to_string())
        .table(Entry::Table)
        .col(Entry::Reading)
        .to_owned()
}

